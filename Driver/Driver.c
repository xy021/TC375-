/* Drive stage of the board HSI_NVS-IK-TP_B00. See Driver.h for the pin table entries and for why switching the
 * valve supply is the same thing as enabling the valve.
 *
 * The supply switches are the reason this file exists at all. A PWM on P20.0 that swings 0 V .. 5 V measures as a
 * clean 2.5 V on a multimeter and looks perfectly healthy, while the valve does nothing at all - because the rail
 * the high side switch pulls its current from is still switched off. Nothing about that failure is visible on the
 * PWM pin, so the two have to be turned on deliberately, in the right order, and read back.                    */

#include "Driver.h"
#include "IfxEvadc_Adc.h"
#include "IfxPort.h"
#include "IfxStm.h"

