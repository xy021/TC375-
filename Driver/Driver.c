/* Writes one of the supply switches. The active level is a macro rather than a literal so that a board that
 * turns out to be wired the other way round is fixed in Driver.h and nowhere else.                             */
static void drvDriveEnablePin(Ifx_P *port, uint8 pin, boolean active, boolean activeHigh)
{
    boolean level = (active == activeHigh);                                    /* TRUE means drive the pin high */

    IfxPort_setPinState(port, pin, level ? IfxPort_State_high : IfxPort_State_low);
}

/* Drives one of the five rail switches and records the raw level in that net's variable, so the two stay in step:
 * applyRailLevels() re-applies those variables every pass of the main loop, so a switch driven without recording
 * it would be undone on the next pass. Every rail switch goes through here for that reason - there is no path that
 * moves one of these pins without moving its variable.                                                      */
static void drvDriveRail(volatile uint32 *rawLevel, Ifx_P *port, uint8 pin, boolean active, boolean activeHigh)
{
    drvDriveEnablePin(port, pin, active, activeHigh);

    *rawLevel = (active == activeHigh) ? 1u : 0u;
}

/* Reads a switch back. This is the pin level, not the level that was asked for - which is the point: a supply
 * that did not come up, or an output that was never switched out of input mode, shows up right here.          */
static boolean drvIsEnablePinActive(Ifx_P *port, uint8 pin, boolean activeHigh)
{
    return (IfxPort_getPinState(port, pin) == TRUE) == activeHigh;
}

/* Blocking delay on STM0. Startup only - the waits below are tens of milliseconds before the main loop is
 * running, and nothing here may be reached from that loop, which must not block.                            */
static void drvDelayMs(uint32 ms)
{
    uint32 ticks = (uint32)IfxStm_getTicksFromMilliseconds(&MODULE_STM0, ms);
    uint32 start = IfxStm_getLower(&MODULE_STM0);

    /* Unsigned subtraction stays correct when the 32 bit STM counter wraps around */
    while ((IfxStm_getLower(&MODULE_STM0) - start) < ticks)
    {
        /* The loop is the delay */
    }
}

/* drvDelayMs() converts milliseconds to STM0 ticks in 32 bits, so above roughly forty seconds the count wraps and
 * the wait comes out shorter than what was asked for - silently, and in the direction that looks like the pulse was
 * ignored. Clamped here so a value typed into the debugger cannot do that. 30 s is far past anything a startup
 * release needs, and a value that large is a typo, not a measurement.                                          */
static void drvOcpDelayMs(uint32 ms)
{
    if (ms > DRIVER_OCP_RECOVER_MAX_MS)
    {
        ms = DRIVER_OCP_RECOVER_MAX_MS;
    }

    drvDelayMs(ms);
}

/* One pulse on OI_RSTOCP_M and back to idle. The board latches an over current in hardware: once it has tripped,
 * the valve keeps its supply but delivers no current, which from the outside is indistinguishable from a supply
 * that never came up. The pin table gives this signal as 脉冲信号，高电平有效 with a pull-down on the net - a
 * pulse, active high, idle low - so clearing the latch is an edge, not a level, and holding the pin either way
 * does nothing. That is why a build that never pulses it looks dead no matter what the rails do.
 *
 * The evidence for it is the board itself: flashing a known good binary and then flashing this one back leaves the
 * valve working, because the other binary pulses this pin and the latch stays cleared afterwards.
 *
 * Public rather than static so a latch that trips while the board is on a bench can be cleared from the debugger,
 * by writing OI_RSTOCP_M, instead of by a rebuild. It is a release, not a retry: it will happily clear a
 * latch that the fault it latched on is still there to set again, so calling it in a loop is not recovery.
 *
 * The width comes from OI_RSTOCP_M_pulse_ms, which the debugger can write. Nothing here is a fixed number any
 * more: the pin is meant to sit on a scope while the width, the gap, the count and the polarity are swept from
 * the debugger, because the pin table gives the signal as a pulse and gives no width for it.               */
void pulseOcpRecovery(void)
{
    setOcpRecovery(TRUE);
    drvOcpDelayMs(OI_RSTOCP_M_pulse_ms);
    setOcpRecovery(FALSE);

    g_driverOcpPulses++;
}

/* The startup release: settle, then a short burst of pulses. See the timing block in Driver.h for why it is a
 * burst and why it waits first - both come down to the protection being powered from the rails this runs after,
 * and to not knowing when in the ramp it latches.
 *
 * The gap and the count are read once here rather than per pass, so a count edited in the debugger while the
 * burst runs does not extend this particular burst. That is deliberate: the burst should end.                 */
static void drvReleaseOcpLatch(void)
{
    uint32 count = OI_RSTOCP_M_count;
    uint8  i;

    /* Bounded, so that a mistyped value cannot hold the boot in this loop. A boot that never finishes and a
     * program that crashed both look like a dark run LED from the outside, and only one of them is a bug.   */
    if (count > DRIVER_OCP_RECOVER_MAX_PULSES)
    {
        count = DRIVER_OCP_RECOVER_MAX_PULSES;
    }

    drvOcpDelayMs(OI_RSTOCP_M_settle_ms);

    for (i = 0u; i < count; i++)
    {
        pulseOcpRecovery();
        drvOcpDelayMs(OI_RSTOCP_M_retry_ms);
    }
}

/* A free running release train, for the scope. The startup burst above is one shot and blocking, which is right
 * for a startup and useless for tuning: it is over before a debugger can type anything into it, so every edit to
 * the width looks like it did nothing. This one repeats until OI_RSTOCP_M_run is written back to 0, and it never
 * blocks, because it runs from the main loop.
 *
 * Non blocking is the whole point, and it is also what makes the edits visible: the width and the period are read
 * on every pass, so a value typed in the debugger takes effect on the phase that is running right now, not on the
 * next pulse. On a scope that is the difference between "nothing happens" and "the high time just changed".
 *
 * It is deliberately not the startup path. Nothing that opens the valve goes through here.                  */
static uint32  g_ocpPhaseStart = 0u;                                           /* STM0 tick this phase began at */
static boolean g_ocpPulseHigh  = FALSE;                                        /* Inside the high part of a pulse */

static void drvStopOcpTrain(void)
{
    g_ocpPulseHigh  = FALSE;
    g_ocpPhaseStart = IfxStm_getLower(&MODULE_STM0);                           /* Re-arm: the first pulse comes one
                                                                                  period after the next write, not
                                                                                  the instant it lands            */
    setOcpRecovery(FALSE);
}

static void drvServiceOcpTrain(void)
{
    uint32 now     = IfxStm_getLower(&MODULE_STM0);
    uint32 phaseMs = g_ocpPulseHigh ? OI_RSTOCP_M_pulse_ms : OI_RSTOCP_M_retry_ms;

    if ((now - g_ocpPhaseStart) < (uint32)IfxStm_getTicksFromMilliseconds(&MODULE_STM0, phaseMs))
    {
        return;                                                                /* Still inside this phase        */
    }

    g_ocpPhaseStart = now;
    g_ocpPulseHigh  = !g_ocpPulseHigh;
    setOcpRecovery(g_ocpPulseHigh);

    if (!g_ocpPulseHigh)
    {
        g_driverOcpPulses++;                                                   /* The falling edge completes one */
    }
}

/* Brings up group 8 with the two monitor channels and leaves it converting in the background.
 * The queue is what makes this cheap: an interrupt driven or polled conversion would need the CPU for every
 * sample, while a refilled queue keeps the result registers fresh on its own. getSv1CurrentMa() and
 * getVddvVoltageMv() then only read a register.                                                               */
static void drvInitAdc(void)
{
    IfxEvadc_Adc_Config        adcConfig;
    IfxEvadc_Adc_GroupConfig   groupConfig;
    IfxEvadc_Adc_ChannelConfig channelConfig;

    /* ---- Module. The analog clock is derived from fSPB, so this is only correct once the CCU is configured -
     * which is why initDriverMonitors() is called after initCcuClock().                                      */
    IfxEvadc_Adc_initModuleConfig(&adcConfig, &MODULE_EVADC);

    g_driverAdcStatus = (uint32)IfxEvadc_Adc_initModule(&g_drvAdc, &adcConfig);

    if (g_driverAdcStatus != (uint32)IfxEvadc_Status_noError)
    {
        return;                                                                /* Why is in g_driverAdcStatus   */
    }

    /* ---- Group 8. Three fields decide whether anything converts at all, and all three default to the wrong
     * value for a free running monitor:                                                                      */
    IfxEvadc_Adc_initGroupConfig(&groupConfig, &g_drvAdc);

    groupConfig.groupId = DRIVER_ADC_GROUP;
    groupConfig.master  = DRIVER_ADC_GROUP;                                    /* Master of itself, not a slave  */

    /* Startup calibration is left off during bring-up. IfxEvadc_startupCalibration() is a do-while with no
     * timeout - it spins until every group's CAL bit clears - so an ADC that is not properly supplied turns
     * bring-up into a hang before the run LED ever starts breathing, with nothing on the board to say why.
     * Calibration only buys accuracy, which nothing here needs yet. Set it back to TRUE once the board is
     * known to run, and restart the group afterwards.                                                       */
    groupConfig.startupCalibration = FALSE;

    /* Without an arbiter slot the queue is configured but never served, and the result registers stay at their
     * reset value forever - with no error anywhere to say so.                                                */
    groupConfig.arbiter.requestSlotQueue0Enabled = TRUE;

    /* Gating is a hardware trigger in front of the queue. "always" means the gate is permanently open, so the
     * queue runs as soon as it is started; the default leaves the gate closed.                               */
    groupConfig.queueRequest[0].triggerConfig.gatingMode = IfxEvadc_GatingMode_always;

    /* waitForStart: the queue does not convert until IfxEvadc_Adc_startQueue() is called. That is the behaviour
     * wanted here - the channels are added first, then the queue is kicked once at the end.                  */
    groupConfig.queueRequest[0].requestSlotStartMode = IfxEvadc_RequestSlotStartMode_waitForStart;

    /* notInitialised (1) is the one to watch for: it means the ADC clock divider could not be derived from
     * the requested analog frequency, and the function returns before the arbiter and the queue are set up.
     * The queue then never runs and every reading stays at the reset value, with no error raised anywhere.  */
    g_driverAdcStatus = (uint32)IfxEvadc_Adc_initGroup(&g_drvAdcGroup, &groupConfig);

    if (g_driverAdcStatus != (uint32)IfxEvadc_Status_noError)
    {
        return;
    }

    /* ---- P40.8 as an analog input. The pad has to leave the digital domain and drop its pull device: a
     * pull-up left connected sits in parallel with the divider on the Vddv rail and scales the reading.      */
    IfxPort_setPinMode(DRIVER_VDDV_VOLTAGE_PORT, DRIVER_VDDV_VOLTAGE_PIN, IfxPort_Mode_inputNoPullDevice);
    IfxPort_setPinFunctionMode(DRIVER_VDDV_VOLTAGE_PORT, DRIVER_VDDV_VOLTAGE_PIN, IfxPort_PinFunctionMode_analog);

    /* ---- SV1 current, AN35. Dedicated analog pin, so there is no port register to configure.                */
    IfxEvadc_Adc_initChannelConfig(&channelConfig, &g_drvAdcGroup);
    channelConfig.channelId      = DRIVER_SV1_CURRENT_CHANNEL;
    channelConfig.resultRegister = DRIVER_SV1_CURRENT_RESULT;
    g_driverAdcStatus = (uint32)IfxEvadc_Adc_initChannel(&g_drvSv1Current, &channelConfig);

    if (g_driverAdcStatus != (uint32)IfxEvadc_Status_noError)
    {
        return;
    }

    /* ---- Vddv rail, AN38 on P40.8.                                                                          */
    IfxEvadc_Adc_initChannelConfig(&channelConfig, &g_drvAdcGroup);
    channelConfig.channelId      = DRIVER_VDDV_VOLTAGE_CHANNEL;
    channelConfig.resultRegister = DRIVER_VDDV_VOLTAGE_RESULT;
    g_driverAdcStatus = (uint32)IfxEvadc_Adc_initChannel(&g_drvVddvVoltage, &channelConfig);

    if (g_driverAdcStatus != (uint32)IfxEvadc_Status_noError)
    {
        return;
    }

    /* Sample time comes from the group input class and is 1 us at the default analog frequency, which is well
     * above the impedance of a shunt plus amplifier. Change groupConfig.inputClass[0].sampleTime before
     * initGroup() if the sense network ever turns out to need longer.                                         */

    /* ---- Queue. Refill is armed on the last entry only: that is what makes the queue start over instead of
     * stopping after one pass, so the two result registers stay fresh with no interrupt and no CPU time.     */
    IfxEvadc_Adc_addToQueue(&g_drvSv1Current,  IfxEvadc_RequestSource_queue0, IFXEVADC_QUEUE_REFILL);
    IfxEvadc_Adc_addToQueue(&g_drvVddvVoltage, IfxEvadc_RequestSource_queue0, IFXEVADC_QUEUE_REFILL);
    IfxEvadc_Adc_startQueue(&g_drvAdcGroup, IfxEvadc_RequestSource_queue0);

    g_driverAdcReady = TRUE;
}

/* -----------------------------------------------------------------------------------------------------------------
 * Bring-up override.
 *
 * One global per net, named exactly as the pin assignment table names it, holding the RAW level of that pin:
 * 1 = the pin is driven high, 0 = driven low. Raw rather than the logical state on purpose - OS_nVddv_M at 0
 * means the valve supply is ON - because raw is the thing the table's 有效 column has already been wrong about,
 * three times, and raw is what a probe on the test point would show.
 *
 *   OS_Vbat1_M   P11.3   1 = Vbat1 on        T398
 *   OS_Vbat2_M   P10.8   1 = Vbat2 on        T396
 *   OS_nVddm_M   P10.7   0 = Vddm on         T400
 *   OS_nVddv_M   P10.4   0 = Vddv on         T384
 *   OS_nGndv_M   P33.0   0 = GNDV on         T387
 *
 * These are variables and not macros because the debugger can write a variable and cannot change a macro on a
 * running target - which is the entire point of them. Write one and the main loop re-applies it on the next pass,
 * no rebuild; all thirty-two combinations take about two minutes to sweep. If none brings Vddv up, the MCU side
 * is finished with and what is left is the board's own Vddv circuit.
 *
 * They start at the state setValveSupply() leaves the board in, and setValveSupply() writes them too - through
 * drvDriveRail() - so the loop re-applies the chain instead of undoing it. Writing one of these overrides the
 * chain from then on; setValveSupply(FALSE) will not put it back.
 *
 * Delete this block, applyRailLevels() and the two calls in core0_main() once the rail behaviour is settled.  */
volatile uint32 OS_Vbat1_M = 1u;
volatile uint32 OS_Vbat2_M = 1u;
volatile uint32 OS_nVddm_M = 0u;
volatile uint32 OS_nVddv_M = 0u;
volatile uint32 OS_nGndv_M = 0u;

/* The functional safety output, P23.4 / T367. Not a supply switch: it feeds the board's FailSafe circuit, which
 * drives the system basis chip, which is what the board's power hangs off. Nothing here drove it before, so it has
 * been sitting at the pull-down level the whole time.
 *
 * Starts at 0 on purpose. 0 is what the board's own pull-down has been holding this pin at since power up, so out
 * of reset nothing about the board changes. Writing 1 is a deliberate, observable experiment, and it is the only
 * thing that moves this pin.
 *
 * If 1 turns out to be the level the board wants, this becomes a normal part of startup and the default moves. If
 * it turns out to hold the rails DOWN instead, that is the answer too - the FailSafe circuit is then gating the
 * supply and the code has to assert it before setValveSupply(). Either way the pin stops being a mystery.      */
volatile uint32 OS_FailSafe_M = 0u;

/* OI_RSTOCP_M is not a level like the five above, it is a trigger. Write it non-zero and the next pass of
 * updateDriverState() sends one release pulse on P11.9 and puts it back to 0, so one write is one pulse and the
 * variable reads 0 again by the time that pulse is over. That is what the signal is - 脉冲信号，高电平有效, a
 * pulse - so it is the edge that releases the latch and the level on either side of it means nothing.
 *
 * The one thing to be careful of: that holds for a write that happens once. A debugger set to refresh a variable
 * continuously writes it again on every refresh, and each of those is another pulse - at a few kHz that is a pulse
 * train on the pin rather than a release. Write it once and let it read back 0.
 *
 * Deliberately named after the net, so it is the same name the pin table, the test point and the debugger use.  */
volatile uint32 OI_RSTOCP_M = 0u;

/* Manual level control for the same pin, for the two things the trigger above cannot do.
 *
 *   0   normal. The pin idles low and OI_RSTOCP_M sends pulses.
 *   1   pin held high. OI_RSTOCP_M is ignored while this is set.
 *   2   pin held low. Same.
 *
 * Held high is the only way to read what "high" actually is on this pin: a meter cannot catch a 1 ms pulse, so
 * the pulsing has to be stopped and the pin left sitting there. Put this back to 0 and the main loop reclaims the
 * pin to idle on the next pass.
 *
 * It is also the only way to find out whether the board wants a level rather than a pulse - which the pin table
 * says it does not, but that column has been wrong about every switch on this board, so it is worth an experiment
 * that costs nothing.                                                                                       */
volatile uint32 OI_RSTOCP_M_manual = 0u;

/* And this is the one that makes the scope useful, because nothing else here repeats.
 *
 *   0   off. The startup burst runs once and is then over.
 *   1   free running train. The pin keeps pulsing, width OI_RSTOCP_M_pulse_ms, period OI_RSTOCP_M_retry_ms,
 *       until this is written back to 0. Non blocking, so the run LED keeps breathing and the main loop is live.
 *
 * It exists because of exactly the trap that makes editing the width look like it does nothing: the startup burst
 * is one shot, so by the time a debugger can write a value the pulse it was meant to shape has already gone out.
 * And a rebuild does not help either - these variables start from their initialisers, so a reset puts the width
 * back to 1 ms no matter what was typed into it. There has to be a pulse that keeps coming, and this is it.
 *
 * Write it before touching the width, then change the width and the period with the train running.           */
volatile uint32 OI_RSTOCP_M_run = 0u;

/* The five values the release is built from, all live at run time so they can be swept from the debugger with a
 * scope parked on T395. They replace what were fixed macros for exactly that reason: a macro cannot be changed on
 * a running target, so tuning the release meant a rebuild per value, which is not a way to find an edge.
 *
 * These are the starting values. Change them in the debugger to change the release; change them here to change
 * what the board starts with.
 *
 *   OI_RSTOCP_M_pulse_ms       width of one pulse
 *   OI_RSTOCP_M_settle_ms      wait after the rails come up, before the burst
 *   OI_RSTOCP_M_retry_ms       gap between the pulses of the burst
 *   OI_RSTOCP_M_count          how many pulses in the burst
 *   OI_RSTOCP_M_active_high    which level is the releasing one. Polarity as a variable too, because that is the
 *                              other half of the experiment and it was a #define before, i.e. a rebuild.
 *
 * OI_RSTOCP_M_pulse_ms is read once per pulse, so lowering it while the burst is running takes effect on the next
 * pulse. The other four are read once, when the burst starts.
 *
 * There is no variable here for the height of the pulse, and there cannot be one. P11.9 is a push-pull digital
 * pad: pin high means the pad is connected to its own supply and pin low means it is connected to ground, so the
 * high level is whatever that supply is, on every pin of the port, and software has no way to set it to anything
 * else. The 5 V measured on P11.3 (T398) is a property of the port, not of the code that drove it. A GPIO either
 * gives you that one level or nothing.
 *
 * The only software knob that changes the height of a digital output is switching the pad to open drain, where
 * the high level is then set by a pull-up on the net instead of by the pad. That does not apply here: the pin
 * table gives this net a pull-DOWN, so an open drain P11.9 would pull low and never come up at all.
 *
 * So of the three things the pulse is made of - width, polarity and height - two are above and the third is the
 * port supply. Use OI_RSTOCP_M_manual = 1 to stop the pin pulsing and park it high, and the meter reads the
 * height directly.                                                                                          */
volatile uint32 OI_RSTOCP_M_pulse_ms    = DRIVER_OCP_RECOVER_PULSE_MS;
volatile uint32 OI_RSTOCP_M_settle_ms   = DRIVER_OCP_RECOVER_SETTLE_MS;
volatile uint32 OI_RSTOCP_M_retry_ms    = DRIVER_OCP_RECOVER_RETRY_MS;
volatile uint32 OI_RSTOCP_M_count       = DRIVER_OCP_RECOVER_PULSES;
volatile uint32 OI_RSTOCP_M_active_high = DRIVER_OCP_RECOVER_ACTIVE_HIGH ? 1u : 0u;

/* The two analog monitors, named after their nets in the table as well. These are observations and not commands:
 * writing one from the debugger does nothing, updateDriverState() overwrites it on the next pass.            */
volatile uint32 IA_Vddv_M     = 0u;                                            /* AN38, millivolts, point T141  */
volatile uint32 IA_M_LsCurSv1 = 0u;                                            /* AN35, milliamps               */

/* What the five switch pins read back, in the order the net names are listed above. No net name of its own,
 * because it is not a net - it is five of them. This is the one that tells a pin which never left input mode
 * apart from a rail that stayed down; the five command variables above cannot, they hold what was asked for. */
volatile uint32 g_driverPinLevels = 0u;

/* Release pulses this build has completed - one before the rails and OI_RSTOCP_M_count of them after, so six on a
 * normal startup, plus one for every write to OI_RSTOCP_M, plus every pulse the free running train produces. It
 * exists because the pulse itself cannot be seen without a scope, so "the latch did not clear" and "the code never
 * pulsed" look identical from outside. If this reads 1 + OI_RSTOCP_M_count and the valve is still shut, the code
 * did its part: what is left is the polarity, or the board.
 *
 * While OI_RSTOCP_M_run is set this climbs on its own, which is how the train is confirmed to be running without
 * a scope in front of you.                                                                                  */
volatile uint32 g_driverOcpPulses = 0u;

/* Drives the five switches to whatever the five net variables say. Five register writes against a loop that
 * already spends 200 us in delays, so calling it every pass costs nothing measurable.                      */
void applyRailLevels(void)
{
    IfxPort_setPinState(DRIVER_VBAT1_ENABLE_PORT, DRIVER_VBAT1_ENABLE_PIN, OS_Vbat1_M ? IfxPort_State_high : IfxPort_State_low);
    IfxPort_setPinState(DRIVER_VBAT2_ENABLE_PORT, DRIVER_VBAT2_ENABLE_PIN, OS_Vbat2_M ? IfxPort_State_high : IfxPort_State_low);
    IfxPort_setPinState(DRIVER_VDDM_ENABLE_PORT,  DRIVER_VDDM_ENABLE_PIN,  OS_nVddm_M ? IfxPort_State_high : IfxPort_State_low);
    IfxPort_setPinState(DRIVER_VDDV_ENABLE_PORT,  DRIVER_VDDV_ENABLE_PIN,  OS_nVddv_M ? IfxPort_State_high : IfxPort_State_low);
    IfxPort_setPinState(DRIVER_GNDV_ENABLE_PORT,  DRIVER_GNDV_ENABLE_PIN,  OS_nGndv_M ? IfxPort_State_high : IfxPort_State_low);

    /* Not a supply switch, but written from here so the debugger can move it with the same one-variable write as
     * the five above. See the block that defines OS_FailSafe_M.                                           */
    IfxPort_setPinState(DRIVER_FAILSAFE_PORT, DRIVER_FAILSAFE_PIN, OS_FailSafe_M ? IfxPort_State_high : IfxPort_State_low);
}

/* Refreshes the two analog observations and the pin read back from the hardware, and fires the release pulse if
 * OI_RSTOCP_M has been written. Called every pass of the main loop.                                         */
void updateDriverState(void)
{
    /* The manual override wins when it is set: it holds the pin at a level instead of pulsing it, which is the
     * whole reason it exists, so a pulse request arriving during that would defeat the point of setting it.   */
    if (OI_RSTOCP_M_manual != 0u)
    {
        drvStopOcpTrain();
        setOcpRecovery(OI_RSTOCP_M_manual == 1u);
    }
    else if (OI_RSTOCP_M_run != 0u)
    {
        /* Free running train. The manual override above wins over it, so one variable has to be put back before
         * the other takes over - which is the point of them being separate.                                  */
        drvServiceOcpTrain();
    }
    else
    {
        /* Idle. Written every pass so that clearing either of the two above hands the pin back, instead of
         * leaving it wherever that one put it.                                                               */
        drvStopOcpTrain();

        if (OI_RSTOCP_M != 0u)
        {
            /* Cleared before the pulse rather than after, so a write that lands while the pulse is going out is
             * not swallowed. Placed here rather than in the main loop so the caller does not have to know about
             * it, and it is safe at any point after setValveSupply(TRUE) - the rails and the protection behind
             * the pin are both up by then.                                                                   */
            OI_RSTOCP_M = 0u;
            pulseOcpRecovery();
        }
    }

    IA_Vddv_M     = (uint32)getVddvVoltageMv();
    IA_M_LsCurSv1 = (uint32)getSv1CurrentMa();

    g_driverPinLevels = (IfxPort_getPinState(DRIVER_VBAT1_ENABLE_PORT, DRIVER_VBAT1_ENABLE_PIN) ? 1u : 0u)
                      | (IfxPort_getPinState(DRIVER_VBAT2_ENABLE_PORT, DRIVER_VBAT2_ENABLE_PIN) ? 2u : 0u)
                      | (IfxPort_getPinState(DRIVER_VDDM_ENABLE_PORT,  DRIVER_VDDM_ENABLE_PIN)  ? 4u : 0u)
                      | (IfxPort_getPinState(DRIVER_VDDV_ENABLE_PORT,  DRIVER_VDDV_ENABLE_PIN)  ? 8u : 0u)
                      | (IfxPort_getPinState(DRIVER_GNDV_ENABLE_PORT,  DRIVER_GNDV_ENABLE_PIN)  ? 16u : 0u);
}

/* Configures every pin of the drive stage. Parks the five supply switches at the level the board's own reset
 * leaves them at, so nothing this function does changes the state the board powered up in - the two Vbat enables
 * off and the three OS_n*_M rails, Vddm included, on.
 *
 * This is deliberately separate from initDriverMonitors(). The pins are the part the valve needs; the analog
 * monitors are instrumentation, and instrumentation must never be able to stop the load from working. Keeping
 * them in one function means a fault in the ADC takes the valve down with it - which is exactly what happened
 * the first time this ran. Call this after initCcuClock(), then setValveSupply(TRUE), then the monitors.     */
void initDriverStage(void)
{
    /* ---- Step 1: park the supply switches at the level the board's own reset leaves them at, before they become
     * outputs. The level is written while the pin is still an input, so it is already in the output register when
     * the pad switches over - which is what keeps the pad from glitching to the output register's reset value as
     * it switches.
     *
     * That level is 0 V on all five pins. Driver.h lists all five with an external pull-down, so an input reads
     * 0 V, and that is the state the board powers up in. For the two Vbat enables 0 V is also their off level, so
     * those two park off and stay off until setValveSupply() asks for them. For the three OS_n*_M switches 0 V is
     * their *on* level, so they park on.
     *
     * Parking those three anywhere else - at their "off" level, which is how this read for a long time - means
     * driving a live rail off during startup, and it happens before the Vbat rails they are fed from have come
     * up. The rails do not come back from that, and the board then looks dead with all five pins at the levels
     * the known good binary uses. Each of the three is a supply that has to be on, so none of them is ever driven
     * high.                                                                                                  */
    drvDriveRail(&OS_Vbat1_M, DRIVER_VBAT1_ENABLE_PORT, DRIVER_VBAT1_ENABLE_PIN, FALSE, DRIVER_VBAT1_ACTIVE_HIGH);
    drvDriveRail(&OS_Vbat2_M, DRIVER_VBAT2_ENABLE_PORT, DRIVER_VBAT2_ENABLE_PIN, FALSE, DRIVER_VBAT2_ACTIVE_HIGH);
    drvDriveRail(&OS_nVddv_M, DRIVER_VDDV_ENABLE_PORT,  DRIVER_VDDV_ENABLE_PIN,  TRUE,  DRIVER_VDDV_ACTIVE_HIGH);
    drvDriveRail(&OS_nGndv_M, DRIVER_GNDV_ENABLE_PORT,  DRIVER_GNDV_ENABLE_PIN,  TRUE,  DRIVER_GNDV_ACTIVE_HIGH);

    IfxPort_setPinMode(DRIVER_VBAT1_ENABLE_PORT, DRIVER_VBAT1_ENABLE_PIN, IfxPort_Mode_outputPushPullGeneral);
    IfxPort_setPinPadDriver(DRIVER_VBAT1_ENABLE_PORT, DRIVER_VBAT1_ENABLE_PIN, DRIVER_PAD_DRIVER);

    IfxPort_setPinMode(DRIVER_VBAT2_ENABLE_PORT, DRIVER_VBAT2_ENABLE_PIN, IfxPort_Mode_outputPushPullGeneral);
    IfxPort_setPinPadDriver(DRIVER_VBAT2_ENABLE_PORT, DRIVER_VBAT2_ENABLE_PIN, DRIVER_PAD_DRIVER);

    IfxPort_setPinMode(DRIVER_VDDV_ENABLE_PORT, DRIVER_VDDV_ENABLE_PIN, IfxPort_Mode_outputPushPullGeneral);
    IfxPort_setPinPadDriver(DRIVER_VDDV_ENABLE_PORT, DRIVER_VDDV_ENABLE_PIN, DRIVER_PAD_DRIVER);

    IfxPort_setPinMode(DRIVER_GNDV_ENABLE_PORT, DRIVER_GNDV_ENABLE_PIN, IfxPort_Mode_outputPushPullGeneral);
    IfxPort_setPinPadDriver(DRIVER_GNDV_ENABLE_PORT, DRIVER_GNDV_ENABLE_PIN, DRIVER_PAD_DRIVER);

    /* Vddm, the motor supply. Parked on, like the three valve switches above and for the same reason: 0 V is both
     * the board's reset level and this rail's on level, so there is never a cause to drive it high. It is also
     * the rail the valve supply sits behind, so setValveSupply() brings it up ahead of the valve switches.    */
    drvDriveRail(&OS_nVddm_M, DRIVER_VDDM_ENABLE_PORT, DRIVER_VDDM_ENABLE_PIN, TRUE, DRIVER_VDDM_ACTIVE_HIGH);
    IfxPort_setPinMode(DRIVER_VDDM_ENABLE_PORT, DRIVER_VDDM_ENABLE_PIN, IfxPort_Mode_outputPushPullGeneral);
    IfxPort_setPinPadDriver(DRIVER_VDDM_ENABLE_PORT, DRIVER_VDDM_ENABLE_PIN, DRIVER_PAD_DRIVER);

    /* ---- Step 2: the functional safety output. Parked low before the pad becomes an output, which is where the
     * board's pull-down has been holding it anyway, so the switch to output changes nothing on the net. It is then
     * driven from OS_FailSafe_M by the main loop, and that variable starts at 0.                           */
    IfxPort_setPinState(DRIVER_FAILSAFE_PORT, DRIVER_FAILSAFE_PIN, IfxPort_State_low);
    IfxPort_setPinMode(DRIVER_FAILSAFE_PORT, DRIVER_FAILSAFE_PIN, IfxPort_Mode_outputPushPullGeneral);
    IfxPort_setPinPadDriver(DRIVER_FAILSAFE_PORT, DRIVER_FAILSAFE_PIN, DRIVER_PAD_DRIVER);

    /* ---- Step 3: the high side monitor. A pull-down is configured because the net is driven by the board, not
     * by the MCU: with the valve node floating the pin would otherwise read whatever it picked up, and a
     * "valve is on" that came from a floating input is worse than no reading at all.                          */
    IfxPort_setPinMode(DRIVER_SV1_HS_MONITOR_PORT, DRIVER_SV1_HS_MONITOR_PIN, IfxPort_Mode_inputPullDown);

    /* ---- Step 4: the over current recovery output. Parked at its idle level before the pin becomes an output, the
     * same way as the five switches above - the net has a pull-down and the signal is active high, so idle is low
     * and the output register's reset value already is that. It is written anyway so the level is this file's
     * statement rather than the reset value of a register. The pulse itself is sent later, from setValveSupply(),
     * because the protection behind this pin is powered from the rails and a pulse sent before them would go into
     * an unpowered circuit.                                                                                   */
    setOcpRecovery(FALSE);
    IfxPort_setPinMode(DRIVER_OCP_RECOVER_PORT, DRIVER_OCP_RECOVER_PIN, IfxPort_Mode_outputPushPullGeneral);
    IfxPort_setPinPadDriver(DRIVER_OCP_RECOVER_PORT, DRIVER_OCP_RECOVER_PIN, DRIVER_PAD_DRIVER);
}

/* The two analog monitors. Call it last, after the valve supply is already on - it is instrumentation, and
 * nothing about opening the valve depends on it.
 *
 * If this function never returns, g_driverAdcStatus says how far it got and g_driverAdcReady says whether the
 * queue was started, both watchable in the debugger. The valve is unaffected either way.                   */
void initDriverMonitors(void)
{
    drvInitAdc();
}

/* The two upstream switches on their own. In normal operation setValveSupply() drives these, so this is only
 * reached directly when the battery rails are wanted without the valve.                                   */
void setBatteryRails(boolean enable)
{
    drvDriveRail(&OS_Vbat1_M, DRIVER_VBAT1_ENABLE_PORT, DRIVER_VBAT1_ENABLE_PIN, enable, DRIVER_VBAT1_ACTIVE_HIGH);
    drvDriveRail(&OS_Vbat2_M, DRIVER_VBAT2_ENABLE_PORT, DRIVER_VBAT2_ENABLE_PIN, enable, DRIVER_VBAT2_ACTIVE_HIGH);
}

/* Turns the valve supply on or off - the whole chain, in the order the chain has to come up in.
 *
 * Vddv and GNDV are switched together because either one alone leaves the valve without a circuit: Vddv with no
 * GNDV is an open end, GNDV with no Vddv is a shorted one. Both are reached *through* the Vbat rails, because
 * Vddv is derived from them: switching the valve switch with the source still off does nothing except light up
 * two pins, which is what the first board measurement showed.
 *
 * No settling delay is inserted between the steps. The PWM on P20.0 is already running by the time this is called,
 * so the gate of the high side FET is defined the whole way up and the rail simply rises into a driven gate. That
 * ordering is the caller's job - see the sequence in core0_main() - not something this function can enforce.  */
void setValveSupply(boolean enable)
{
    if (enable == TRUE)
    {
        /* One release pulse here, before anything is switched, and the burst again at the end. This first one
         * covers the case the burst cannot: a protection circuit powered from something always on rather than
         * from these rails, which latched on an earlier fault and is sitting there waiting. If it is powered from
         * the rails instead, this pulse goes into an unpowered input and does nothing - which costs nothing.
         *
         * Which of the two it is has not been measured. The pin is already an output by the time this runs, so
         * this is safe either way.                                                                            */
        pulseOcpRecovery();

        setBatteryRails(TRUE);                                                 /* Source first                  */

        /* The motor supply, ahead of the valve supply. It belongs to this chain and has to come up in it, not
         * afterwards in the main loop: bringing Vddv and GNDV up while Vddm is still off leaves the valve supply
         * with no motor supply behind it, and both rails stay dead - all five switch pins at their working levels
         * and nothing on the board. That is a chain order, and this is the function that owns the chain.        */
        drvDriveRail(&OS_nVddm_M, DRIVER_VDDM_ENABLE_PORT, DRIVER_VDDM_ENABLE_PIN, TRUE, DRIVER_VDDM_ACTIVE_HIGH);

        drvDriveRail(&OS_nVddv_M, DRIVER_VDDV_ENABLE_PORT, DRIVER_VDDV_ENABLE_PIN, TRUE, DRIVER_VDDV_ACTIVE_HIGH);
        drvDriveRail(&OS_nGndv_M, DRIVER_GNDV_ENABLE_PORT, DRIVER_GNDV_ENABLE_PIN, TRUE, DRIVER_GNDV_ACTIVE_HIGH);

        /* And last, release the over current latch. This is the step that is easy to leave out and impossible to
         * notice: without it the supply chain comes up exactly as intended and the board still does nothing,
         * because a latched over current holds the power stage off. It is also sticky - it stays set across a
         * reset and only a pulse on this pin clears it, which is why flashing another binary that does pulse it
         * leaves this one working afterwards.
         *
         * This blocks for about a fifth of a second while the release goes out. That is on purpose and it is the
         * only blocking wait in this function - see the timing block in Driver.h.                              */
        drvReleaseOcpLatch();
    }
    else
    {
        /* Down in the reverse order: the valve is disconnected before the rail behind it disappears, so it is
         * never left holding a live supply with nothing switching it.                                       */
        drvDriveRail(&OS_nVddv_M, DRIVER_VDDV_ENABLE_PORT, DRIVER_VDDV_ENABLE_PIN, FALSE, DRIVER_VDDV_ACTIVE_HIGH);
        drvDriveRail(&OS_nGndv_M, DRIVER_GNDV_ENABLE_PORT, DRIVER_GNDV_ENABLE_PIN, FALSE, DRIVER_GNDV_ACTIVE_HIGH);

        drvDriveRail(&OS_nVddm_M, DRIVER_VDDM_ENABLE_PORT, DRIVER_VDDM_ENABLE_PIN, FALSE, DRIVER_VDDM_ACTIVE_HIGH);

        setBatteryRails(FALSE);
    }
}

/* TRUE when every switch in the chain is driving its active level. A FALSE here after setValveSupply(TRUE) is
 * the first thing to check when the valve does not respond - and it says which end of the chain to look at.
 *
 * Vddm is read here because setValveSupply() drives it: it is the motor supply the valve supply sits behind, so a
 * TRUE from this function with Vddm down would be the one answer that sends the search to the wrong end.        */
boolean isValveSupplyOn(void)
{
    return areBatteryRailsOn() &&
           drvIsEnablePinActive(DRIVER_VDDM_ENABLE_PORT, DRIVER_VDDM_ENABLE_PIN, DRIVER_VDDM_ACTIVE_HIGH) &&
           drvIsEnablePinActive(DRIVER_VDDV_ENABLE_PORT, DRIVER_VDDV_ENABLE_PIN, DRIVER_VDDV_ACTIVE_HIGH) &&
           drvIsEnablePinActive(DRIVER_GNDV_ENABLE_PORT, DRIVER_GNDV_ENABLE_PIN, DRIVER_GNDV_ACTIVE_HIGH);
}

/* Same read back, for the upstream switches alone. */
boolean areBatteryRailsOn(void)
{
    return drvIsEnablePinActive(DRIVER_VBAT1_ENABLE_PORT, DRIVER_VBAT1_ENABLE_PIN, DRIVER_VBAT1_ACTIVE_HIGH) &&
           drvIsEnablePinActive(DRIVER_VBAT2_ENABLE_PORT, DRIVER_VBAT2_ENABLE_PIN, DRIVER_VBAT2_ACTIVE_HIGH);
}

/* Drives OI_RSTOCP_M, the hardware over current recovery output. assert means "releasing"; whether releasing is
 * a high or a low level comes from OI_RSTOCP_M_active_high, which the debugger can write, so the polarity can be
 * flipped on a running target with the scope still connected. Asserting it does nothing on its own - the signal is
 * a pulse, so it has to be asserted and let go again, which is what pulseOcpRecovery() above does. Left callable
 * so the pin can be driven by hand from the debugger.
 *
 * What is NOT here, and cannot be: the height of the pulse. See the note above these variables in Driver.h.  */
void setOcpRecovery(boolean assert)
{
    drvDriveEnablePin(DRIVER_OCP_RECOVER_PORT, DRIVER_OCP_RECOVER_PIN, assert, (OI_RSTOCP_M_active_high != 0u));
}

/* Reads the SV1 high side monitor, net IS_M_HsSv1. Measured against the known good binary it is 0 V while the
 * valve is working and 0 V while it is not, so a FALSE from here is NOT evidence of a fault - it only becomes
 * meaningful once the polarity of the signal is known from the schematic. Left as a plain level read until then. */
boolean isSv1HighSideOn(void)
{
    return IfxPort_getPinState(DRIVER_SV1_HS_MONITOR_PORT, DRIVER_SV1_HS_MONITOR_PIN);
}

/* Latest SV1 low side current, raw 12 bit value. Reads a result register the queue keeps refilling, so this
 * never waits for a conversion. Returns 0 before initDriverMonitors() has run, when the register would still hold
 * its reset value and a zero would otherwise look like a real measurement.                                 */
uint16 getSv1CurrentRaw(void)
{
    if (g_driverAdcReady == FALSE)
    {
        return 0u;
    }

    return IfxEvadc_Adc_getResult(&g_drvSv1Current).B.RESULT;
}

/* Same reading in milliamps, using the factor printed in the pin assignment table. */
float32 getSv1CurrentMa(void)
{
    return (float32)getSv1CurrentRaw() * DRIVER_SV1_CURRENT_MA_PER_LSB;
}

/* Latest valve supply voltage, raw 12 bit value, net IA_Vddv_M. */
uint16 getVddvRaw(void)
{
    if (g_driverAdcReady == FALSE)
    {
        return 0u;
    }

    return IfxEvadc_Adc_getResult(&g_drvVddvVoltage).B.RESULT;
}

/* Same reading in millivolts. With the valve supply commanded on, this is the measurement that says whether the
 * rail actually came up or is being held down by a short.                                                  */
float32 getVddvVoltageMv(void)
{
    return (float32)getVddvRaw() * DRIVER_VDDV_VOLTAGE_MV_PER_LSB;
}
