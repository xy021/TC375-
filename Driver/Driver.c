/* Both analog monitors land on group 8. The board spreads its analog pins over several groups, and these two are
 * the ones that belong to this group - AN35 is a dedicated analog pin with no port logic behind it, AN38 is
 * P40.8 and has to be switched out of the digital domain first.                                                */
#define DRIVER_ADC_GROUP            IfxEvadc_GroupId_8
#define DRIVER_SV1_CURRENT_AN       35                                         /* AN35                   */
#define DRIVER_VDDV_VOLTAGE_AN      38                                         /* AN38, pin P40.8        */

#define DRIVER_SV1_CURRENT_CHANNEL  IfxEvadc_ChannelId_3                       /* Group 8, AN35          */
#define DRIVER_VDDV_VOLTAGE_CHANNEL IfxEvadc_ChannelId_6                       /* Group 8, AN38 / P40.8  */

#define DRIVER_VDDV_VOLTAGE_PORT    (&MODULE_P40)
#define DRIVER_VDDV_VOLTAGE_PIN     8

/* Two channels cannot share one result register - the second conversion would overwrite the first one's result
 * and one of the two readings would silently be the other channel's.                                            */
#define DRIVER_SV1_CURRENT_RESULT   IfxEvadc_ChannelResult_0
#define DRIVER_VDDV_VOLTAGE_RESULT  IfxEvadc_ChannelResult_1

