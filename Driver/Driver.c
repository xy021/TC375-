/*------------------------------------------------Global Variables---------------------------------------------------*/
/*********************************************************************************************************************/
static IfxEvadc_Adc         g_drvAdc;                                          /* Module handle                 */
static IfxEvadc_Adc_Group   g_drvAdcGroup;                                     /* Group the channels live in    */
static IfxEvadc_Adc_Channel g_drvSv1Current;                                   /* AN35                          */
static IfxEvadc_Adc_Channel g_drvVddvVoltage;                                  /* AN38                          */

/* These two are deliberately not static, so they can be watched in the debugger by name.
 * Without them "the ADC never came up" and "the voltage really is 0 V" are indistinguishable from the outside
 * - both give a 0 from the getters - and the two call for completely different next steps.              */
boolean g_driverAdcReady  = FALSE;                                             /* TRUE once the queue runs      */
uint32  g_driverAdcStatus = 0xFFFFFFFFu;                                       /* Last IfxEvadc_Status, 0 = ok  */

