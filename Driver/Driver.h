/* ---- Hardware over current release, OI_RSTOCP_M (P11.9, point T395) ----------------------------------------------
 * The board latches an over current in hardware and holds it across a reset. Only a pulse on this pin clears it -
 * the signal is 脉冲信号，高电平有效 with a pull-down on the net, so it is idle low and the release is an edge,
 * not a level. A build that never pulses it leaves the power stage held off, which looks exactly like a supply
 * fault and is why this was invisible for so long.
 *
 * setValveSupply(TRUE) already sends the pulse, at the end, once the rails and the protection behind them are
 * powered. These two are for the debugger and for a later recovery step, not for the open-valve path.        */
void    setOcpRecovery(boolean assert);                                        /* Drive the pin, active high     */
void    pulseOcpRecovery(void);                                                /* Low-high-low: clears the latch */

boolean isSv1HighSideOn(void);                                                 /* IS_M_HsSv1 as a logic level   */

/* Analog monitors. Instrumentation, call it last - see the note in Driver.c. */
void    initDriverMonitors(void);

