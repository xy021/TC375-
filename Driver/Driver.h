/* The functional safety output. Not part of the supply chain, and not driven by anything in this file until now -
 * which is exactly why it is here.
 *
 *   P23.4   OS_FailSafe_M   T367   输出   功能安全输出信号   高电平有效
 *
 * The block diagram puts it upstream of the board's own power control: OS_FailSafe_M feeds a FailSafe hardware
 * circuit, which drives OS_FailSafe_SBC into the TLE9471-3ES system basis chip, and that chip is what the board's
 * rails hang off. Nothing in this project has ever driven it, so it has been sitting at its pull-down level since
 * power up while everything else was poked at. If the FailSafe circuit gates the supply switches, that alone would
 * hold every rail down with all five switch pins at exactly the levels the working binary uses - which is the
 * board's behaviour right now.
 *
 * Deliberately NOT driven anywhere except from OS_FailSafe_M, and that variable starts at 0, so out of reset this
 * pin is electrically what it has always been: an input held low by the board's pull-down. Writing the variable to
 * 1 is the experiment, and it is the only thing that changes.                                                 */
#define DRIVER_FAILSAFE_PORT        (&MODULE_P23)
#define DRIVER_FAILSAFE_PIN         4                                          /* Net OS_FailSafe_M, point T367 */

/* Timing of the startup release on OI_RSTOCP_M. None of these four is a measured value - the pin table gives the
 * signal as a pulse and no width, and there is no schematic - so they are chosen to cover the two things that
 * could make a single pulse miss:
 *
 *   the protection is powered from the rails the release is sent after, so it cannot see a pulse the instant they
 *   come up. SETTLE_MS waits for them first.
 *   it may latch during the rail ramp itself, ahead of any release, in which case a pulse sent at one fixed moment
 *   can land before the latch it was meant to clear. PULSES pulses RETRY_MS apart span a window wide enough to be
 *   after it either way.
 *
 * PULSES is deliberately small. This is a startup release, not an auto-retry: if a real over current is present
 * the latch sets again straight away and repeating the pulse faster will not change that.
 *
 * If the release still does not take, widen the window before touching anything else - SETTLE_MS 20 -> 100 and
 * PULSES 5 -> 20 costs a fifth of a second at boot and removes the timing question entirely.
 *
 * None of these four is what the code actually runs on any more. They are the power-on values of the four
 * variables declared further down, which the debugger can write while the pin sits on a scope. Given no width in
 * the table and no schematic to derive one from, the way to find the edge is to sweep it, not to rebuild per
 * value. Change these to change what the board starts with, or just write the variables.                     */
#define DRIVER_OCP_RECOVER_PULSE_MS     1                                      /* Width of one release pulse    */
#define DRIVER_OCP_RECOVER_SETTLE_MS    20                                     /* Wait after the rails come up  */
#define DRIVER_OCP_RECOVER_RETRY_MS     20                                     /* Gap between release pulses    */
#define DRIVER_OCP_RECOVER_PULSES       5                                      /* Number of release pulses      */

/* Ceiling on OI_RSTOCP_M_count, so a mistyped value in the debugger cannot hold the boot in the release loop.
 * 100 pulses of the default 20 ms gap is two seconds - long, but clearly finite and clearly not a hang.    */
#define DRIVER_OCP_RECOVER_MAX_PULSES   100

/* Ceiling on the three millisecond variables. drvDelayMs() builds its tick count in 32 bits, so a value above
 * roughly forty seconds wraps and the wait comes out shorter than asked - silently, and in the direction that
 * looks like the pulse was ignored. See drvOcpDelayMs() in Driver.c.                                        */
#define DRIVER_OCP_RECOVER_MAX_MS       30000

/* Slowest pad slew rate. These are static logic levels, nothing switches here faster than the application asks
 * it to, and a soft edge keeps the supply switches from radiating into the valve current measurement.          */
#define DRIVER_PAD_DRIVER           IfxPort_PadDriver_cmosAutomotiveSpeed1

/* ---- Analog monitors ---------------------------------------------------------------------------------------------
 * Both conversion factors are taken from the pin assignment table. The current one already includes the shunt and
 * the amplifier gain that sit in front of the pin, and the voltage one the divider on the Vddv rail, so the raw
 * value only has to be multiplied to become a physical quantity.                                               */
#define DRIVER_SV1_CURRENT_MA_PER_LSB   0.61035f                              /* AN35, i = AD * 0.61035 mA     */
#define DRIVER_VDDV_VOLTAGE_MV_PER_LSB  8.6805f                               /* AN38, u = AD * 8.6805 mV      */

