/* ---- Bring-up variables -------------------------------------------------------------------------------------------
 * One global per net, named exactly as the pin assignment table names it. Variables and not macros because the
 * debugger can write a variable on a running target and cannot change a macro - which is the whole point of them.
 * applyRailLevels() and updateDriverState() are both called from the main loop.
 *
 * Raw pin level, 1 = driven high. Not the logical state: OS_nVddv_M at 0 means the valve supply is ON. Raw is
 * what the table's 有效 column has already been wrong about three times, and raw is what a probe would show.
 *
 *   OS_Vbat1_M   P11.3  T398   1 = Vbat1 on     writable
 *   OS_Vbat2_M   P10.8  T396   1 = Vbat2 on     writable
 *   OS_nVddm_M   P10.7  T400   0 = Vddm on      writable
 *   OS_nVddv_M   P10.4  T384   0 = Vddv on      writable
 *   OS_nGndv_M   P33.0  T387   0 = GNDV on      writable
 *   OS_FailSafe_M P23.4 T367   1 = safety output asserted. Starts at 0, so writing 1 is the experiment
 *
 * Write any of the six and the main loop re-applies it on the next pass, no rebuild. That overrides the chain
 * from then on: setValveSupply(FALSE) will not put it back.
 *
 * OS_FailSafe_M is the odd one out: it is not a supply switch and Driver.c never touches it except from this
 * variable. It is here because the block diagram puts it upstream of the board's own power control - see the
 * block that defines DRIVER_FAILSAFE_PORT. It starts at 0, which is the level the board's pull-down has been
 * holding it at all along, so it changes nothing until it is written.
 *
 *   OI_RSTOCP_M         P11.9  T395   write non-zero to send one release pulse, then it clears itself
 *   OI_RSTOCP_M_run     P11.9  T395   write non-zero to free run the pulse train. This is the one to write first
 *   OI_RSTOCP_M_manual  P11.9  T395   0 = normal, 1 = hold the pin high, 2 = hold it low
 *
 * OI_RSTOCP_M is a trigger and not a level - the signal is 脉冲信号，高电平有效, so it is the edge that releases
 * the latch. This is how the release gets tested by hand; pulseOcpRecovery() does the same thing but a debugger
 * cannot generally call a function.
 *
 * The manual variable overrides it while it is non-zero, which is how the level gets measured: a meter cannot
 * catch a pulse, so the pin has to be stopped from pulsing and left sitting at the level instead. Set it
 * back to 0 and the main loop returns the pin to idle.
 *
 * The five below say what the release pulse is made of, and they exist because a macro cannot be changed on a
 * running target. Park the scope on T395, then sweep these from the debugger - no rebuild per value.
 *
 *   OI_RSTOCP_M_pulse_ms      width of one pulse, milliseconds. Also the width the free running train uses.
 *   OI_RSTOCP_M_settle_ms     wait after the rails come up, before the startup burst starts
 *   OI_RSTOCP_M_retry_ms      gap between pulses. Also the period of the free running train.
 *   OI_RSTOCP_M_count         how many pulses in the startup burst, capped at DRIVER_OCP_RECOVER_MAX_PULSES
 *   OI_RSTOCP_M_active_high   1 = the releasing level is high, 0 = it is low
 *
 * Note the split: _pulse_ms and _retry_ms are live, read on every pass of the main loop, so a change to either is
 * on the scope immediately - but only while the train is running. _count and _settle_ms shape the startup burst
 * and nothing else, so they can only be exercised by a reset.
 *
 * And a reset loses every edit: these are variables with initialisers, so the startup code puts the defaults back.
 * Any value typed into the debugger applies to the session it was typed in and to no other. That is the reason the
 * train exists - without something that repeats, there is nothing for a typed value to affect.
 *
 * What is not here, and cannot be: the height of the pulse. P11.9 is a push-pull digital pad, so its high level is
 * its port supply and no value written to any variable changes that - the only software route to a different
 * height is open drain, which needs a pull-up on the net and this net has a pull-down. To see the height, set
 * OI_RSTOCP_M_manual = 1 and measure the parked pin.
 *
 * The four at the end are observations, not commands. Writing them from the debugger does nothing -
 * updateDriverState() overwrites them every pass. The two analog ones hold physical quantities in the units the
 * pin table gives, not raw levels; g_driverPinLevels is a read back and g_driverOcpPulses a count, and neither has
 * a net of its own.                                                                                         */
extern volatile uint32 OS_Vbat1_M;
extern volatile uint32 OS_Vbat2_M;
extern volatile uint32 OS_nVddm_M;
extern volatile uint32 OS_nVddv_M;
extern volatile uint32 OS_nGndv_M;
extern volatile uint32 OS_FailSafe_M;
extern volatile uint32 OI_RSTOCP_M;
extern volatile uint32 OI_RSTOCP_M_manual;
extern volatile uint32 OI_RSTOCP_M_run;
extern volatile uint32 OI_RSTOCP_M_pulse_ms;
extern volatile uint32 OI_RSTOCP_M_settle_ms;
extern volatile uint32 OI_RSTOCP_M_retry_ms;
extern volatile uint32 OI_RSTOCP_M_count;
extern volatile uint32 OI_RSTOCP_M_active_high;

