/* ---- Power rail switches ------------------------------------------------------------------------------------------
 * Five switches, wired up as a chain - Vddv has no source of its own, it is fed from the Vbat rails:
 *
 *   P11.3  OS_Vbat1_M   电源Vbat1开启控制    高电平有效      T398
 *   P10.8  OS_Vbat2_M   电源Vbat2开启控制    高电平有效      T396
 *   P10.7  OS_nVddm_M   电机电源Vddm关断控制 高电平有效      T400
 *   P10.4  OS_nVddv_M   阀电源Vddv关断控制   高电平有效      T384
 *   P33.0  OS_nGndv_M   GNDV电源关断控制信号 高电平有效      T387
 *
 * That last column is right for the two Vbat enables and wrong for the three 关断 pins. P11.3 and P10.8 are 5 V and
 * their rails measure 13.16 V and 13.23 V on IA_Vbat1_M and IA_Vbat2_M, so those two do what the table says.
 *
 * The 关断 pair is inverted, and the net names say so out loud: OS_nVddv_M and OS_nGndv_M both carry the "n", so
 * both are active low. The table called them 高电平有效 anyway, and that one word is what this whole bring-up
 * kept tripping over:
 *
 *   working state, against a known good binary
 *   P11.3 = 5 V   P10.8 = 5 V   P10.4 = 0 V   P33.0 = 0 V   P10.7 = 0 V
 *   Vddv = 13.3 V (IA_Vddv_M = 1.87 V)   Vddm = 13.3 V (IA_Vddm_M = 1.87 V)
 *
 * Both were driven high at first; when Vddv measured 3.67 V the pair was flipped together to low, which was half
 * right and got read as half wrong. The rule is the "n" in the net name, not the 有效 column.
 *
 * OS_nVddm_M (P10.7, T400) follows the same rule, and the working binary shows it: P10.7 sits at 0 V there and
 * IA_Vddm_M measures 1.87 V, so the Vddm rail is up at 13.3 V with the pin low. That makes all three OS_n*_M
 * nets active low, table or no table.
 *
 * Vddm is the motor supply rather than the valve supply, but it is a switch of this chain and comes up in it,
 * ahead of the two valve switches - the motor supply live is what lets the valve supply live do anything. It used
 * to be left out of setValveSupply() and driven only from the main loop, which put it up *after* the two switches
 * it has to be up before, and made it depend on a block of code that is meant to be deleted.
 *
 * The GNDV level is also what made the rail look broken for so long. With GNDV off, IA_Vddv_M is not a rail
 * measurement at all - the node floats, so it reads something that means nothing. GNDV has to be on before that
 * sense point can be trusted, so setValveSupply() drives both of them in the same call rather than leaving the
 * return to the caller. Which of the two goes first within that call does not seem to matter: a solenoid does
 * not care, and the high side FET is already switching by then either way.                                  */
#define DRIVER_VBAT1_ACTIVE_HIGH    TRUE                                       /* P11.3 high switches Vbat1 on  */
#define DRIVER_VBAT2_ACTIVE_HIGH    TRUE                                       /* P10.8 high switches Vbat2 on  */
#define DRIVER_VDDV_ACTIVE_HIGH     FALSE                                      /* P10.4 LOW switches Vddv on    */
#define DRIVER_GNDV_ACTIVE_HIGH     FALSE                                      /* P33.0 LOW switches GNDV on    */
#define DRIVER_VDDM_ACTIVE_HIGH     FALSE                                      /* P10.7 LOW switches Vddm on    */

/* P11.9 is the one exception to the rule above, and it is not a switch: the net has no "n" in it and the table
 * calls it 脉冲信号，高电平有效 - a pulse, active high. Its pull-down puts the idle level at 0 V, which agrees.
 * The power-on value only. Column J has been wrong for every switch on this board, so if a release pulse does
 * nothing, the polarity is the first thing to flip - and that is what OI_RSTOCP_M_active_high is for, so it can be
 * flipped with the target running instead of by rebuilding.                                                    */
#define DRIVER_OCP_RECOVER_ACTIVE_HIGH  TRUE                                   /* P11.9 high releases the latch */

