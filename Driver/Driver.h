float32 getSv1CurrentMa(void);                                                 /* AN35, milliamps               */
uint16  getVddvRaw(void);                                                      /* AN38, raw 12 bit value        */
float32 getVddvVoltageMv(void);                                                /* AN38, millivolts              */

