/* Drive stage (驱动级) of the board HSI_NVS-IK-TP_B00: everything between the MCU pins and the load.
 *
 * ALT.c gets a signal *out* of a pin. That signal is only the command. This file does the rest of what has to be
 * true before the load - here the SV1 stiffness valve - actually does something:
 *
 *   1. turn the switched valve supply on. P20.0 toggles between two levels; with Vddv or GNDV switched off there
 *      is no current behind those levels, so the valve stays shut no matter what frequency or duty cycle is set.
 *      This is not one switch but a chain - Vddv is derived from the Vbat rails, so the Vbat enables come first.
 *      Bringing up only the valve switch leaves all of Vbat1, Vbat2 and Vddv at about 1.5 V of leakage.
 *   2. configure the feedback pins, so the result can be checked instead of guessed. The high side monitor says
 *      whether the valve node really came up, and the two analog monitors give the current and the rail voltage.
 *
 * Pin assignment table entries used here (HSI_NVS-IK-TP_B00):
 *
 *   P10.4   OS_nVddv_M      output   电源管理     阀电源Vddv关断控制         T384
 *   P33.0   OS_nGndv_M      output   电源         GNDV电源关断控制信号      T387
 *   P11.3   OS_Vbat1_M      output   电源管理     电源Vbat1开启控制          T398
 *   P10.8   OS_Vbat2_M      output   电源管理     电源Vbat2开启控制          T396
 *   P02.0   IS_M_HsSv1      input    刚度阀控制    Sv1高边电压监测
 *   P11.9   OI_RSTOCP_M     output   硬件过流保护  硬件过流保护恢复信号
 *   AN35    IA_M_LsCurSv1   analog   刚度阀控制    Sv1电流采集,   i = AD * 0.61035 mA
 *   AN38    IA_Vddv_M       analog   电源管理      阀电源Vddv检知, u = AD * 8.6805 mV
 *
 * Note that SV1 appears in the table only as the PWM output, the high side monitor and the current sense. There is
 * no driver enable pin per valve: the gate driver and the power stage sit on the board and are live as soon as the
 * rails are. That is why switching the supply is the whole of the "enable".
 */

