void initCan1(void);                                                           /* 初始化 CAN1，含 SBC 收发器上电 */
void can1Service(void);                                                        /* 主循环里调用，处理发送请求     */

/*********************************************************************************************************************/
/*---------------------------------------------QSPI3 / PSI5 pin mux---------------------------------------------------*/
/*********************************************************************************************************************/
/* 板载 7 路 PSI5 传感器（4 路高度 Level_*，3 路加速度 ACC_*），走 QSPI3 + 两颗 ELMOS E521.41 收发器：
 *
 *   U360（下面那颗）= trx1，管 4 路高度：片选 NCS1 = P02.8，复位 NRES1 = P14.8，触发 TRIG1 = P14.7
 *   U388（上面那颗）= trx2，管 3 路加速度：片选 NCS2 = P00.5，复位 NRES2 = P14.1，触发 TRIG2 = P14.6
 *
 * 引脚分配表（这一段的每一根都在表里对过）：
 *
 *   引脚分配表  P02.5  ID_Psi5SdoQspi3_M   QSPI3_MRSTA   输入   收发器的 SDO -> MCU
 *   引脚分配表  P02.6  OD_Psi5SdiQspi3_M   QSPI3_MTSRA   输出   MCU -> 收发器的 SDI
 *   引脚分配表  P02.7  OD_Psi5ClkQspi3_M   QSPI3_SCLKA   输出
 *   引脚分配表  P02.8  OS_Psi5Ncs1Qspi3_M  QSPI3_SLSO5   输出   trx1 片选
 *   引脚分配表  P00.5  OS_Psi5Ncs2Qspi3_M  QSPI3_SLSO3   输出   trx2 片选
 *                      （表里功能列写的是 "General-purpose input"，那是错的：网表名 OS_ 就是 output，
 *                        iLLD 里也只有 IfxQspi3_SLSO3_P00_5_OUT 这一个条目，按输出用）
 *   引脚分配表  P14.8  OS_Psi5Nres1_M      普通 GPIO     输出   trx1 复位，低有效
 *   引脚分配表  P14.1  OS_Psi5Nres2_M      普通 GPIO     输出   trx2 复位，低有效
 *   引脚分配表  P14.7  OS_Psi5Trig1_M      普通 GPIO     输出   本板不用，钉在低电平
 *   引脚分配表  P14.6  OS_Psi5Trig2_M      普通 GPIO     输出   本板不用，钉在低电平
 *
 * iLLD 里的条目（IfxQspi_PinMap.c）：
 *
 *   IfxQspi3_MRSTA_P02_5_IN    {&MODULE_QSPI3, {&MODULE_P02, 5}, Ifx_RxSel_a}
 *   IfxQspi3_MTSR_P02_6_OUT    复用号 alt3
 *   IfxQspi3_SCLK_P02_7_OUT    复用号 alt3
 *   IfxQspi3_SLSO5_P02_8_OUT   slsoNr 5，复用号 alt2
 *   IfxQspi3_SLSO3_P00_5_OUT   slsoNr 3，复用号 alt3
 *
 * 符号本身已经把"哪个 QSPI 内核、哪根片选、哪个端口、第几位、哪个复用号"全带上了，所以下面除了
 * 推挽/输入/驱动强度之外没有别的要填。
 *
 * NRES 是低有效的复位/测试模式脚，E521 内部有 70..130k 下拉。上电时先让它保持低（复位），
 * QSPI 配好、两根片选都由硬件驱动在不选中电平（高）之后，再把它拉高 —— E521 在 NRES 上升沿
 * 那一下看 NCS 的电平决定进 SPI 还是 UART 接口模式，NCS 高才是 SPI。所以 ALT_initPsi5CtrlPins()
 * 里四根脚先写输出锁存低电平再切成推挽输出，拉高 NRES 的动作在 qspi.c 的 initQspi() 里做。       */
static inline const IfxQspi_SpiMaster_Pins *ALT_getQspi3Pins(void)
{
    static const IfxQspi_SpiMaster_Pins qspi3Pins = {
        &IfxQspi3_SCLK_P02_7_OUT,                /* P02.7，QSPI3_SCLKA，输出，alt3    */
        IfxPort_OutputMode_pushPull,
        &IfxQspi3_MTSR_P02_6_OUT,                /* P02.6，QSPI3_MTSRA，输出，alt3    */
        IfxPort_OutputMode_pushPull,
        &IfxQspi3_MRSTA_P02_5_IN,                /* P02.5，QSPI3_MRSTA，输入          */
        IfxPort_InputMode_pullDown,
        IfxPort_PadDriver_cmosAutomotiveSpeed1
    };

    return &qspi3Pins;
}

