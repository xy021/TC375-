/* Application limits taken from the pin assignment table for every stiffness valve
 * ("2-60kHz, frequency and spread spectrum parameters configurable"). These are limits of the valve and of the
 * driver stage, not of the timer, so they are not enforced here - see SV1_PWM_TICKS_MAX in ALT.c for the range the
 * hardware can actually produce.                                                                                    */
#define SV1_PWM_MIN_FREQ_HZ  2000.0f
/* Lowest allowed valve frequency       */
#define SV1_PWM_MAX_FREQ_HZ  60000.0f                                          /* Highest allowed valve frequency      */

/* Reset values for the two variables below, and the fallback used when one of them holds something the timer
 * cannot be programmed with. They are no longer what the PWM runs at - OP_M_HsSv1_freq_hz and
 * OP_M_HsSv1_duty_pct are.                                                                                 */
#define SV1_PWM_INIT_FREQ_HZ 20000.0f                                          /* Frequency applied by initSv1Pwm()    */
#define SV1_PWM_INIT_DUTY_PCT 0.0f                                            /* Duty cycle applied by initSv1Pwm()   */

/*********************************************************************************************************************/
/*-----------------------------------------------Debugger variables--------------------------------------------------*/
/*********************************************************************************************************************/
/* The two knobs the debugger writes, for the board net OP_M_HsSv1 (P20.0, GTM_TOUT59). Plain globals named after
 * the net and not macros, so a value typed into the debugger reaches the pin without a rebuild.
 *
 *   OP_M_HsSv1_freq_hz   frequency to run at, in Hz
 *   OP_M_HsSv1_duty_pct  high time, 0 .. 100 percent
 *
 * initSv1Pwm() reads them once, and updateSv1PwmFromVariables() watches them from the main loop afterwards, so a
 * write takes effect within one pass of the loop.
 *
 * Both are written back by the code with the value the timer actually ended up programmed to. What the debugger
 * shows after a write is therefore the truth and not the request: asking for 1000 Hz shows 1526, because that is
 * the lowest the 16 bit counter can reach from a 100 MHz clock, and asking for 150 percent shows 100.
 *
 * The pin assignment table gives 2 kHz .. 60 kHz for this net. That is a limit of the valve and of the driver
 * stage, not of the timer, so it is not enforced - see the note on SV1_PWM_MIN_FREQ_HZ above.               */
extern volatile float32 OP_M_HsSv1_freq_hz;
extern volatile float32 OP_M_HsSv1_duty_pct;

