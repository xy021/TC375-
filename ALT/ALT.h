/* Alternate function (引脚复用) outputs of the board HSI_NVS-IK-TP_B00.
 * Nothing in here talks to a GPIO data register: every signal leaves through a peripheral that owns the pin
 * internally, so the peripheral has to be configured and the pin has to be switched to the matching
 * alternate function. Both halves are done inside the iLLD call that takes the pin map entry.
 *
 * First signal implemented: SV1 high side, board net OP_M_HsSv1, pin P20.0.
 * The pin assignment table lists it as GTM_TOUT59 and iLLD carries the matching entry
 * IfxGtm_TOM0_6_TOUT59_P20_0_OUT - TOM0 channel 6, TOUTSEL_a selecting TOUT59, pin P20.0 as Alt1.
 */

