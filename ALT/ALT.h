/* 板载 RTC 是 Seiko Epson RA4000CE，4 线 SPI，挂在 QSPI1 上：
 *
 *   引脚分配表  P10.1  ID_RtcDoQspi1_M    QSPI1_MRSTA   输入   RTC 的 DO -> MCU
 *   引脚分配表  P10.2  OD_RtcClkQspi1_M   QSPI1_SCLKA   输出   SCLK
 *   引脚分配表  P10.3  OD_RtcDiQspi1_M    QSPI1_MTSRA   输出   MCU -> RTC 的 DI
 *   引脚分配表  P11.11 OS_RtcNcsQspi1_M   QSPI1_SLSO4   输出   CE
 *   引脚分配表  P11.12 IS_RtcAwa_M        普通 GPIO     输入   RTC 的 /INT，开漏低有效
 *
 * iLLD 里的条目（IfxQspi_PinMap.c）：
 *
 *   IfxQspi1_MRSTA_P10_1_IN    {&MODULE_QSPI1, {&MODULE_P10, 1}, Ifx_RxSel_a}
 *   IfxQspi1_MTSR_P10_3_OUT    复用号 alt3
 *   IfxQspi1_SCLK_P10_2_OUT    复用号 alt3
 *   IfxQspi1_SLSO4_P11_11_OUT  slsoNr 4，复用号 alt4
 *
 * 注意 P11.11 这根片选：网表叫 "NCS"（低有效的外观），但 RA4000CE 数据手册里 CE 是高有效 ——
 * CE 拉低会取消传输，芯片内部自带下拉。所以 rtc.c 里 csActiveLevel 给的是 Ifx_ActiveState_high，
 * iLLD 会把 SSOC.AOL[4] 置 1，SLSO4 空闲低、选中高。名字别被骗了。
 *
 * P11.12 是 RTC 的 /INT 输出（N 沟道开漏，低有效），MCU 这边只做输入，所以选 pullUp：
 * 没有中断时线上是高的，RTC 拉低就是唤醒信号。                                     */
static inline const IfxQspi_SpiMaster_Pins *ALT_getQspi1Pins(void)
{
    static const IfxQspi_SpiMaster_Pins qspi1Pins = {
        &IfxQspi1_SCLK_P10_2_OUT,                /* P10.2，QSPI1_SCLKA，输出，alt3    */
        IfxPort_OutputMode_pushPull,
        &IfxQspi1_MTSR_P10_3_OUT,                /* P10.3，QSPI1_MTSRA，输出，alt3    */
        IfxPort_OutputMode_pushPull,
        &IfxQspi1_MRSTA_P10_1_IN,                /* P10.1，QSPI1_MRSTA，输入          */
        IfxPort_InputMode_pullUp,
        IfxPort_PadDriver_cmosAutomotiveSpeed1
    };

    return &qspi1Pins;
}

static inline const IfxQspi_SpiMaster_Output *ALT_getRtcCePin(void)
{
    static const IfxQspi_SpiMaster_Output rtcCePin = {
        &IfxQspi1_SLSO4_P11_11_OUT,              /* P11.11，QSPI1_SLSO4，输出，alt4   */
        IfxPort_OutputMode_pushPull,
        IfxPort_PadDriver_cmosAutomotiveSpeed1
    };

    return &rtcCePin;
}

static inline void ALT_initRtcAwaPin(void)
{
    IfxPort_setPinModeInput(&MODULE_P11, 12, IfxPort_InputMode_pullUp);
}

/* P11.12 的电平：1 = 没有唤醒请求，0 = RTC 正在拉低 /INT。 */
static inline uint8 ALT_getRtcAwaLevel(void)
{
    return (IfxPort_getPinState(&MODULE_P11, 12) != FALSE) ? 1u : 0u;
}

