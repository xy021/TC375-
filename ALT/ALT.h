/* 四根普通 GPIO：NRES1/NRES2 低有效复位，TRIG1/TRIG2 不用、钉低。
 * 先写输出锁存再切输出模式，切成输出的那一刻引脚上就是低电平，不会先冒一个高脉冲出去。 */
static inline void ALT_initPsi5CtrlPins(void)
{
    IfxPort_setPinState(&MODULE_P14, 8, IfxPort_State_low);   /* P14.8 NRES1 */
    IfxPort_setPinState(&MODULE_P14, 1, IfxPort_State_low);   /* P14.1 NRES2 */
    IfxPort_setPinState(&MODULE_P14, 7, IfxPort_State_low);   /* P14.7 TRIG1 */
    IfxPort_setPinState(&MODULE_P14, 6, IfxPort_State_low);   /* P14.6 TRIG2 */

    IfxPort_setPinModeOutput(&MODULE_P14, 8, IfxPort_OutputMode_pushPull, IfxPort_OutputIdx_general);
    IfxPort_setPinModeOutput(&MODULE_P14, 1, IfxPort_OutputMode_pushPull, IfxPort_OutputIdx_general);
    IfxPort_setPinModeOutput(&MODULE_P14, 7, IfxPort_OutputMode_pushPull, IfxPort_OutputIdx_general);
    IfxPort_setPinModeOutput(&MODULE_P14, 6, IfxPort_OutputMode_pushPull, IfxPort_OutputIdx_general);

    IfxPort_setPinPadDriver(&MODULE_P14, 8, IfxPort_PadDriver_cmosAutomotiveSpeed1);
    IfxPort_setPinPadDriver(&MODULE_P14, 1, IfxPort_PadDriver_cmosAutomotiveSpeed1);
    IfxPort_setPinPadDriver(&MODULE_P14, 7, IfxPort_PadDriver_cmosAutomotiveSpeed1);
    IfxPort_setPinPadDriver(&MODULE_P14, 6, IfxPort_PadDriver_cmosAutomotiveSpeed1);
}

/* 拉高/拉低两颗 E521 的复位脚。上电顺序见 Qspi/qspi.c 的 initQspi()。 */
static inline void ALT_setPsi5Nres1(boolean high)
{
    IfxPort_setPinState(&MODULE_P14, 8, (high != FALSE) ? IfxPort_State_high : IfxPort_State_low);
}

static inline void ALT_setPsi5Nres2(boolean high)
{
    IfxPort_setPinState(&MODULE_P14, 1, (high != FALSE) ? IfxPort_State_high : IfxPort_State_low);
}

