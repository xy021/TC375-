/* 板载 CAN1 的引脚复用。CAN1 的收发器不在这块板上单独存在，它在 SBC（U104，TLE9471-3ES）里面，
 * 所以 MCU 这边只有两根线：
 *
 *   引脚分配表第 78 行  P33.8  OD_Can1TxCan00_M  CAN00_TXD   输出   MCU -> SBC 的 TXDCAN
 *   引脚分配表第 77 行  P33.7  ID_Can1RxCan00_M  CAN00_RXDE  输入   SBC 的 RXD -> MCU
 *
 * 和 iLLD 里的条目一一对应（IfxCan_PinMap.c 第 86 行和第 49 行）：
 *   IfxCan_TXD00_P33_8_OUT   {&MODULE_CAN0, IfxCan_NodeId_0, {&MODULE_P33, 8}, IfxPort_OutputIdx_alt5}
 *   IfxCan_RXD00E_P33_7_IN   {&MODULE_CAN0, IfxCan_NodeId_0, {&MODULE_P33, 7}, Ifx_RxSel_e}
 * 这两个符号本身就把"哪个 CAN 内核、哪个节点、哪个端口、第几位、哪个复用号"全带上了，所以下面除了
 * 推挽/输入/驱动强度之外没有别的要填。
 *
 * 名字里的 00 是 CAN00 这个内核的编号，不是端口 P00 —— CAN2 用的那两根 P33.4/P33.5 在 iLLD 里叫
 * CAN13（MODULE_CAN1 + NodeId_3）。这块板上两个通道的编号差得很远，不要按 P33.4 -> P33.8 的顺序去猜。
 *
 * RXD 选 pullUp：SBC 的 RXD 是推挽输出，正常情况下不需要上拉；但 SBC 在 Stop/Sleep 状态下 RXD 会
 * 停在高阻，这时上拉把它定在隐性电平，CAN00 看到的就是总线空闲，而不是一根飘着的线。
 * 发送用 pushPull、驱动强度 cmosAutomotiveSpeed2，和 CAN2（P33.4/P33.5）保持一致。            */
static inline const IfxCan_Can_Pins *ALT_getCan1Pins(void)
{
    static const IfxCan_Can_Pins can1Pins = {
        &IfxCan_TXD00_P33_8_OUT,                 /* P33.8，CAN00_TXD，输出，alt5      */
        IfxPort_OutputMode_pushPull,
        &IfxCan_RXD00E_P33_7_IN,                 /* P33.7，CAN00_RXDE，输入           */
        IfxPort_InputMode_pullUp,
        IfxPort_PadDriver_cmosAutomotiveSpeed2
    };

    return &can1Pins;
}

